'use strict';

const assert = require('node:assert/strict');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {before, after, test} = require('node:test');
const root = path.resolve(__dirname, '..');
const source = path.join(__dirname, 'PartialMultianewarrayRegression.java');
const className = 'classes.modern_test.PartialMultianewarrayRegression';
const runtime = path.join(root, 'build/release-cli');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
let temporary, classes, generated, java, layoutReader, decoder, sourceHash, fixtureHash, runtimeHash;
function checked(command, args) {
  const result = cp.spawnSync(command, args, {cwd: temporary, encoding: 'utf8', timeout: 60000,
    maxBuffer: 1024 * 1024, env: {...process.env, DOPPIO_VERIFY_SOURCE: ''}});
  assert.equal(result.error, undefined, String(result.error)); assert.equal(result.signal, null);
  assert.equal(result.status, 0, (result.stdout + result.stderr).slice(-6000)); return result;
}
function fixtureDigest(directory) {
  const values = [];
  function visit(current) {
    for (const name of fs.readdirSync(current).sort()) {
      const filename = path.join(current, name), stat = fs.lstatSync(filename);
      if (stat.isDirectory()) visit(filename);
      else {
        assert.ok(stat.isFile() && !stat.isSymbolicLink());
        values.push([path.relative(directory, filename), sha(fs.readFileSync(filename))]);
      }
    }
  }
  visit(directory); return sha(JSON.stringify(values));
}
function allocations(bytes, methodName) {
  const layout = layoutReader(bytes), methods = layout.methods.entries.filter(entry => entry.name === methodName);
  assert.equal(methods.length, 1, methodName); const code = methods[0].code; assert.ok(code);
  return decoder(bytes.subarray(code.instructionsOffset, code.instructionsOffset + code.codeLength), layout.pool, bytes)
    .filter(instruction => ['newarray', 'anewarray', 'multianewarray'].includes(instruction.name));
}
before(async () => {
  ({readStructureLayout: layoutReader} = await import('./java_class_structure_test.mjs'));
  ({decodeCoreCode: decoder} = await import('./java_core_bytecode.mjs'));
  const {treeDigest} = await import('./prepare_java_compatibility_toolchains.mjs');
  const {validateToolchains} = await import('./run_java_compatibility.mjs');
  const lockBytes = fs.readFileSync(path.join(__dirname, 'java_compatibility_toolchains.lock.json'));
  const lock = JSON.parse(lockBytes);
  const marker = JSON.parse(fs.readFileSync(path.join(root, 'build/java-compatibility-toolchains/toolchains.json')));
  validateToolchains(marker, lock, sha(lockBytes), [21, 25]);
  const pinned = marker.toolchains.find(entry => entry.feature === 25);
  assert.equal(treeDigest(pinned.home), lock.toolchains.find(entry => entry.feature === 25).treeSha256,
    'Original locked Java25 SDK tree');
  java = path.join(pinned.home, 'bin/java');
  temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'doppio-partial-multianewarray-')); fs.chmodSync(temporary, 0o700);
  classes = path.join(temporary, 'classes'); const empty = path.join(temporary, 'empty');
  fs.mkdirSync(classes); fs.mkdirSync(empty); generated = path.join(temporary, 'original-generated.class');
  sourceHash = sha(fs.readFileSync(source));
  runtimeHash = sha(fs.readFileSync(path.join(runtime, 'src/ClassData.js')));
  checked(path.join(pinned.home, 'bin/javac'), ['--release', '25', '-encoding', 'UTF8', '-proc:none', '-g:source',
    '-sourcepath', empty, '-classpath', empty, '-d', classes, source]);
  fixtureHash = fixtureDigest(classes);
  console.log('PARTIAL_MULTIANEWARRAY_INPUTS|' + sourceHash + '|' + fixtureHash + '|' + runtimeHash);
});
after(() => {
  try {
    if (sourceHash) assert.equal(sha(fs.readFileSync(source)), sourceHash, 'Unchanged original Java source');
    if (fixtureHash) assert.equal(fixtureDigest(classes), fixtureHash, 'No fixture bytes rewritten by either host');
    if (runtimeHash) assert.equal(sha(fs.readFileSync(path.join(runtime, 'src/ClassData.js'))), runtimeHash,
      'Actual built guest runtime stays unchanged during this test');
  } finally { if (temporary) fs.rmSync(temporary, {recursive: true, force: true}); }
});
test('original javac25 controls and native generated bytes contain their genuine allocation operands', () => {
  const bytes = fs.readFileSync(path.join(classes, 'classes/modern_test/PartialMultianewarrayRegression.class'));
  assert.equal(bytes.readUInt16BE(6), 69);
  for (const [family, type] of [['Reference', '[[[Ljava.lang.String;'], ['Primitive', '[[[I']]) {
    assert.equal(allocations(bytes, 'direct' + family + 'One')[0].name, 'anewarray');
    for (const [suffix, dimensions] of [['Two', 2], ['Full', 3]]) {
      const instructions = allocations(bytes, 'direct' + family + suffix); assert.equal(instructions.length, 1);
      assert.equal(instructions[0].name, 'multianewarray'); assert.equal(instructions[0].dimensions, dimensions);
      assert.equal(instructions[0].cp.tag, 7); assert.equal(instructions[0].cp.value, type);
    }
  }
  assert.equal(allocations(bytes, 'directRankOne')[0].name, 'newarray');
  assert.equal(allocations(bytes, 'directRankOne')[0].arrayType, 10);
  const direct = checked(java, ['-cp', classes, className, 'direct']);
  assert.equal(direct.stdout, 'PARTIAL_MULTIANEWARRAY_DIRECT_OK|41\n'); assert.equal(direct.stderr, '');
  const native = checked(java, ['-cp', classes, className, 'generated', 'produce', generated]);
  assert.equal(native.stdout, 'PARTIAL_MULTIANEWARRAY_GENERATED_OK|41\n'); assert.equal(native.stderr, '');
  const original = fs.readFileSync(generated); assert.equal(original.readUInt16BE(6), 69);
  for (const [family, type] of [['reference', '[[[Ljava.lang.String;'], ['primitive', '[[[I']]) {
    for (const [suffix, dimensions] of [['One', 1], ['Two', 2], ['Full', 3]]) {
      const instructions = allocations(original, family + suffix); assert.equal(instructions.length, 1);
      assert.equal(instructions[0].opcode, 197); assert.equal(instructions[0].dimensions, dimensions);
      assert.equal(instructions[0].cp.tag, 7); assert.equal(instructions[0].cp.value, type);
    }
  }
  const rankOne = allocations(original, 'rankOne'); assert.equal(rankOne.length, 1);
  assert.equal(rankOne[0].opcode, 197); assert.equal(rankOne[0].dimensions, 1);
  assert.equal(rankOne[0].cp.tag, 7); assert.equal(rankOne[0].cp.value, '[I');
  console.log('PARTIAL_MULTIANEWARRAY_NATIVE_OK|82|' + sha(original));
});
test('actual Node guest preserves ordinary partial/full reference and primitive allocations', () => {
  const result = checked(process.execPath, ['--no-deprecation', path.join(runtime, 'console/runner.js'),
    '-cp', classes, className, 'direct']);
  assert.equal(result.stdout, 'PARTIAL_MULTIANEWARRAY_DIRECT_OK|41\n'); assert.equal(result.stderr, '');
});
test('actual Node guest executes the exact native-generated MULTIANEWARRAY bytes for dimensions1/rank1', () => {
  const original = fs.readFileSync(generated), originalHash = sha(original);
  const result = checked(process.execPath, ['--no-deprecation', path.join(runtime, 'console/runner.js'),
    '-cp', classes, className, 'generated', 'consume', generated]);
  assert.equal(result.stdout, 'PARTIAL_MULTIANEWARRAY_GENERATED_OK|41\n'); assert.equal(result.stderr, '');
  assert.equal(sha(fs.readFileSync(generated)), originalHash, 'Native-produced class bytes unchanged by guest');
});
